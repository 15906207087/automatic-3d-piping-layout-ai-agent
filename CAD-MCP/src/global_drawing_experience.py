"""
全局绘图经验库。

这个模块只保留可跨任务复用的通用经验、错误模式、校验步骤和流程建议，
不记录仅适用于单个案例、单个设备或单次调参结果的细节。

设计目标：
1. 在开始建模前，先做结构化的任务准备，而不是直接开画。
2. 在建模中，把“漏件、错件、方向错、法兰无孔、保存失败”这类高频问题前置规避。
3. 在建模后，强制走截图校验和部件清单复核，减少反复返工。
4. 在经验回写时，先把案例现象抽象成可迁移规则，再决定是否入库。
"""

from __future__ import annotations

from dataclasses import dataclass, asdict
from typing import Dict, List


@dataclass(frozen=True)
class DrawingLesson:
    """单条绘图经验。"""

    title: str
    stage: str
    problem: str
    action: str
    value: str


@dataclass(frozen=True)
class ErrorPattern:
    """单条错误模式与处理策略。"""

    error_name: str
    symptom: str
    probable_cause: str
    mitigation: str
    prevention: str


@dataclass(frozen=True)
class ReviewCheckpoint:
    """绘图校验点。"""

    category: str
    check_items: List[str]


